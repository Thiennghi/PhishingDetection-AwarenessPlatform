#!/usr/bin/env python3
"""Compile one reviewed JSON source into browser data and SQL seed. No dependencies."""
import json,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
k=json.loads((root/'data/detection-knowledge.json').read_text())
ids={s['id'] for s in k['sources']}
assert len({r['id'] for r in k['rules']})==len(k['rules'])
for r in k['rules']:
 assert all(s in ids for s in r['sources']),r['id']
 assert 0<=r['weight']<=100
payload=json.dumps(k,ensure_ascii=False,separators=(',',':'))
browser = ('// Generated by scripts/build_detection_data.py; edit the canonical JSON.\nwindow.PhishingDataset = '+payload+';\n')
def literal(value):
 # Hex literals avoid SQL-mode-dependent backslash escaping and quoting.
 return "CONVERT(0x"+str(value).encode().hex()+" USING utf8mb4)"
sql=['-- Generated source/rule seed. Run as schema owner after 003_detection.sql.','USE cyberguard_db;','START TRANSACTION;']
for s in k['sources']:
 vals=','.join(literal(s[x]) for x in ['id','publisher','title','url','reviewed_on'])
 sql.append('INSERT INTO detection_sources (source_id,publisher,title,url,reviewed_on) VALUES ('+vals+') ON DUPLICATE KEY UPDATE publisher=VALUES(publisher), title=VALUES(title),url=VALUES(url),reviewed_on=VALUES(reviewed_on);')
# Remove only the previous authored rules, not threat feeds or history.
sql.append('DELETE FROM detection_rules;')
for r in k['rules']:
 vals=','.join(literal(v) for v in [r['id'],k['version'],json.dumps(r,separators=(',',':'))])
 sql.append('INSERT INTO detection_rules (rule_id,dataset_version,rule_json) VALUES ('+vals+');')
sql.append('COMMIT;')
seed = '\n'.join(sql)+'\n'
dump = (root/'cyberguard_db.sql').read_text().split('-- Generated source/rule seed.')[0] + seed
outputs = {'phishingData.js':browser,'data/detection_seed.sql':seed,'cyberguard_db.sql':dump}
for name, content in outputs.items():
 if '--check' in sys.argv:
  if (root/name).read_text() != content: raise SystemExit('Generated file is stale: '+name)
 else: (root/name).write_text(content)
print(f"Built {len(k['rules'])} rules and {len(k['sources'])} sources, version {k['version']}")
